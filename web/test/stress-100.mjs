function syntheticPdf() {
  const fontId = 203;
  const objects = [
    '<< /Type /Catalog /Pages 2 0 R >>',
    `<< /Type /Pages /Kids [${Array.from({ length: 100 }, (_, i) => `${3 + i * 2} 0 R`).join(' ')}] /Count 100 >>`,
  ];
  for (let page = 1; page <= 100; page++) {
    const lines = ['0 0 0 rg', `BT /F1 16 Tf 40 790 Td (PDF to TIFF stress test - page ${String(page).padStart(3, '0')} of 100) Tj ET`];
    for (let row = 0; row < 45; row++) {
      lines.push(`BT /F1 9 Tf 40 ${760 - row * 13} Td (Question ${row + 1}: sample questionnaire text, page ${page}. Name: __________________  Answer: Yes / No) Tj ET`);
    }
    lines.push('0.6 w');
    for (let row = 0; row <= 8; row++) lines.push(`40 ${50 + row * 12} m 555 ${50 + row * 12} l S`);
    for (let col = 0; col <= 5; col++) lines.push(`${40 + col * 103} 50 m ${40 + col * 103} 146 l S`);
    // Same marker contract as the real questionnaire fixture generated by Python.
    lines.push('1 1 1 rg 18 4 50 9 re f', '0 0 0 rg');
    for (let bit = 0; bit < 8; bit++) if (bit === 7 || page & (1 << bit)) lines.push(`${20 + bit * 5} 6 3 5 re f`);
    const content = lines.join('\n') + '\n';
    objects.push(`<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595.276 841.89] /Resources << /Font << /F1 ${fontId} 0 R >> >> /Contents ${4 + (page - 1) * 2} 0 R >>`, `<< /Length ${Buffer.byteLength(content)} >>\nstream\n${content}endstream`);
  }
  objects.push('<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica /Encoding /WinAnsiEncoding >>');
  assert.equal(objects.length, fontId);
  let text = '%PDF-1.4\n';
  const offsets = [0];
  for (const [i, object] of objects.entries()) {
    offsets.push(Buffer.byteLength(text));
    text += `${i + 1} 0 obj\n${object}\nendobj\n`;
  }
  const xref = Buffer.byteLength(text);
  text += `xref\n0 ${objects.length + 1}\n0000000000 65535 f \n`;
  for (const offset of offsets.slice(1)) text += `${String(offset).padStart(10, '0')} 00000 n \n`;
  text += `trailer\n<< /Size ${objects.length + 1} /Root 1 0 R >>\nstartxref\n${xref}\n%%EOF\n`;
  return Buffer.from(text);
}

function tiffTags(bytes) {
  const view = new DataView(bytes.buffer, bytes.byteOffset, bytes.byteLength);
  assert.equal(view.getUint16(0, true), 0x4949);
  assert.equal(view.getUint16(2, true), 42);
  const ifd = view.getUint32(4, true), count = view.getUint16(ifd, true), tags = {};
  for (let i = 0; i < count; i++) {
    const entry = ifd + 2 + i * 12, tag = view.getUint16(entry, true), type = view.getUint16(entry + 2, true), length = view.getUint32(entry + 4, true);
    const size = { 3: 2, 4: 4, 5: 8 }[type];
    assert.ok(size, `supported field type ${type}`);
    const start = length * size > 4 ? view.getUint32(entry + 8, true) : entry + 8;
    assert.ok(start + length * size <= bytes.length);
    tags[tag] = Array.from({ length: type === 5 ? length * 2 : length }, (_, j) => type === 3 ? view.getUint16(start + j * 2, true) : view.getUint32(start + j * 4, true));
  }
  assert.equal(view.getUint32(ifd + 2 + count * 12, true), 0, 'exactly one TIFF page per file');
  return tags;
}
const popcount = Uint8Array.from({ length: 256 }, (_, n) => n.toString(2).replaceAll('0', '').length);
function decodeAndCheck(bytes, expectedPage) {
  const t = tiffTags(bytes);
  for (const [tag, value] of Object.entries({ 256: [3308], 257: [4678], 258: [1], 259: [32773], 262: [0], 277: [1], 282: [400, 1], 283: [400, 1], 296: [2] })) assert.deepEqual(t[tag], value, `page ${expectedPage}, tag ${tag}`);
  const width = t[256][0], height = t[257][0], rowBytes = Math.ceil(width / 8), rowsPerStrip = t[278][0];
  assert.equal(t[273].length, t[279].length);
  const bitmap = new Uint8Array(rowBytes * height);
  let blackPixels = 0;
  for (let strip = 0; strip < t[273].length; strip++) {
    let source = t[273][strip], dest = strip * rowsPerStrip * rowBytes;
    const sourceEnd = source + t[279][strip], end = Math.min((strip + 1) * rowsPerStrip, height) * rowBytes;
    while (source < sourceEnd && dest < end) {
      const header = bytes[source++];
      if (header < 128) {
        const length = header + 1;
        assert.ok(source + length <= sourceEnd && dest + length <= end);
        bitmap.set(bytes.subarray(source, source + length), dest); source += length; dest += length;
      } else if (header > 128) {
        const length = 257 - header;
        assert.ok(source < sourceEnd && dest + length <= end);
        bitmap.fill(bytes[source++], dest, dest + length); dest += length;
      }
    }
    assert.equal(dest, end, 'whole strip decoded');
    assert.equal(source, sourceEnd, 'no unconsumed strip bytes');
  }
  for (const value of bitmap) blackPixels += popcount[value];
  const pixel = (x, y) => bitmap[y * rowBytes + (x >> 3)] & (0x80 >> (x & 7)) ? 0 : 255;
  let pageMarker = 0;
  for (let bit = 0; bit < 8; bit++) {
    const x = Math.floor((21.5 + bit * 5) * 400 / 72), y = Math.floor((841.89 - 8.5) * 400 / 72);
    const black = pixel(x, y) === 0;
    if (bit === 7) assert.ok(black, `page ${expectedPage} marker sentinel`);
    else if (black) pageMarker |= 1 << bit;
  }
  assert.equal(pageMarker, expectedPage, 'unique page marker preserves every page and ordering');
  assert.ok(blackPixels > width * height * 0.01, `page ${expectedPage} is not blank/marker-only`);
  assert.ok(blackPixels < width * height * 0.5, `page ${expectedPage} is not all black`);
  return { page: expectedPage, width, height, bytes: bytes.length, blackPercent: Math.round(10000 * blackPixels / (width * height)) / 100, marker: pageMarker, sha256: createHash('sha256').update(bytes).digest('hex') };
}

const input = process.env.PDF_TO_TIFF_STRESS_INPUT ? path.resolve(process.env.PDF_TO_TIFF_STRESS_INPUT) : path.join(output, 'synthetic-100-a4.pdf');
if (!process.env.PDF_TO_TIFF_STRESS_INPUT) await writeFile(input, syntheticPdf());
const report = {
  startedAt: new Date().toISOString(), platform: process.platform, browser: browserName,
  html: path.relative(repo, html), htmlSha256: createHash('sha256').update(await readFile(html)).digest('hex'),
  input: path.relative(repo, input), inputBytes: (await readFile(input)).length, inputSha256: createHash('sha256').update(await readFile(input)).digest('hex'),
  source: process.env.PDF_TO_TIFF_STRESS_INPUT ? 'custom-marked-pdf' : 'synthetic-text-and-table',
  settings: { pages: 100, dpi: 400, color: 'bw', compression: 'packbits', output: 'separate', download: 'zip' },
  networkRequests: [], pageErrors: [], consoleErrors: [], warnings: [], progress: [], pages: [],
};
let browser;
try {
  assert.ok(['chromium', 'chrome', 'msedge'].includes(browserName));
  browser = await chromium.launch({ headless: true, ...(browserName === 'chromium' ? {} : { channel: browserName }) });
  const context = await browser.newContext({ offline: true, acceptDownloads: true, viewport: { width: 1100, height: 1200 } });
  context.on('request', request => { if (/^https?:/i.test(request.url())) report.networkRequests.push(request.url()); });
  await context.route(/^https?:/i, route => route.abort('internetdisconnected'));
  const page = await context.newPage();
  page.on('pageerror', error => report.pageErrors.push(error.message));
  page.on('console', message => { if (message.type() === 'error') report.consoleErrors.push(message.text()); if (message.type() === 'warning') report.warnings.push(message.text()); });
  let downloads = 0;
  page.on('download', () => downloads++);
  await page.exposeFunction('stressProgress', text => {
    report.progress.push({ milliseconds: Math.round(performance.now() - report.runStart), text });
    console.log(text);
  });
  await page.goto(pathToFileURL(html).href, { waitUntil: 'load' });
  report.userAgent = await page.evaluate(() => navigator.userAgent);
  await page.locator('#pdf-file').setInputFiles(input);
  for (const [selector, value] of Object.entries({ '#dpi': '400', '#color-mode': 'bw', '#compression': 'packbits', '#output-mode': 'separate', '#download-mode': 'zip' })) await page.locator(selector).selectOption(value);
  await page.evaluate(() => {
    let last = '';
    new MutationObserver(() => {
      const text = document.getElementById('status').textContent;
      const match = text.match(/страницу (\d+) из/);
      if (text !== last && (match ? Number(match[1]) % 10 === 0 : true)) { last = text; window.stressProgress(text); }
    }).observe(document.getElementById('status'), { childList: true, subtree: true });
  });
  report.runStart = performance.now();
  await page.locator('#convert').click();
  await page.waitForFunction(() => !document.getElementById('convert').disabled, null, { timeout: 600_000 });
  report.conversionMilliseconds = Math.round(performance.now() - report.runStart);
  report.status = await page.locator('#status').textContent();
  assert.match(report.status, /^Готово\. Страниц: 100\./);
  assert.ok(await page.locator('#download').isVisible());
  assert.equal(downloads, 0, 'conversion does not download automatically');
  assert.equal(await page.locator('#download').textContent(), 'Скачать ZIP с TIFF');
  report.generatedAt = await page.locator('#result-created-time').getAttribute('datetime');
  const pending = page.waitForEvent('download');
  const downloadStart = performance.now();
  await page.locator('#download').click();
  const download = await pending;
  assert.equal(await download.failure(), null);
  const zipPath = path.join(output, download.suggestedFilename());
  await download.saveAs(zipPath);
  report.downloadMilliseconds = Math.round(performance.now() - downloadStart);
  assert.equal(downloads, 1);
  assert.equal(await page.locator('#result-created-time').getAttribute('datetime'), report.generatedAt);
  const zip = new Uint8Array(await readFile(zipPath));
  report.zip = path.relative(repo, zipPath); report.zipBytes = zip.length;
  report.zipSha256 = createHash('sha256').update(zip).digest('hex');
  const files = unzipSync(zip), names = Object.keys(files).sort();
  assert.equal(names.length, 100);
  const checkStart = performance.now();
  for (const [i, name] of names.entries()) {
    assert.ok(name.endsWith(`_page_${String(i + 1).padStart(3, '0')}.tiff`));
    report.pages.push({ name, ...decodeAndCheck(files[name], i + 1) });
  }
  report.validationMilliseconds = Math.round(performance.now() - checkStart);
  report.tiffBytes = report.pages.reduce((sum, p) => sum + p.bytes, 0);
  assert.deepEqual(report.networkRequests, []); assert.deepEqual(report.pageErrors, []); assert.deepEqual(report.consoleErrors, []);
  await page.screenshot({ path: path.join(output, 'browser.png'), fullPage: true });
  report.passed = true;
} catch (error) {
  report.passed = false; report.failure = error.stack; process.exitCode = 1; console.error(error);
} finally {
  if (browser) await browser.close();
  delete report.runStart;
  report.completedAt = new Date().toISOString();
  await writeFile(path.join(output, 'report.json'), JSON.stringify(report, null, 2) + '\n');
  console.log(JSON.stringify({ passed: report.passed, pages: report.pages.length, conversionMilliseconds: report.conversionMilliseconds, downloadMilliseconds: report.downloadMilliseconds, zipBytes: report.zipBytes, tiffBytes: report.tiffBytes, errors: report.pageErrors, networkRequests: report.networkRequests.length, report: path.join(output, 'report.json') }, null, 2));
}
